using System;
using System.Collections.Generic;
using System.Text;

namespace Alternet.UI
{
    /// <summary>
    /// Specifies the scroll bars to be displayed in a control or container.
    /// </summary>
    public enum ScrollBars
    {
        /// <summary>
        /// No scroll bars are shown.
        /// </summary>
        None,

        /// <summary>
        /// Only horizontal scroll bars are shown.
        /// </summary>
        Horizontal,

        /// <summary>
        /// Only vertical scroll bars are shown.
        /// </summary>
        Vertical,

        /// <summary>
        /// Both horizontal and vertical scroll bars are shown.
        /// </summary>
        Both,
    }
}
