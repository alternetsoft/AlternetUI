using System;
using System.Collections.Generic;
using System.Text;

namespace Alternet.UI
{
    /// <summary>
    /// Specifies how vertical text should be drawn.
    /// </summary>
    public enum VerticalTextDirection
    {
        /// <summary>
        /// Characters flow from bottom to top.
        /// </summary>
        BottomToTop,

        /// <summary>
        /// Characters flow from top to bottom.
        /// </summary>
        TopToBottom,
    }
}
